//! Integration tests for the full JSON -> `SuitManifest` -> CBOR pipeline.
//!
//! These exist because the `cddl` crate (the obvious off-the-shelf validator) has confirmed
//! bugs against real SUIT CDDL (see `docs/cddl-crate-map-groupname-bug.md`) and cannot be
//! trusted as a conformance oracle. Instead:
//!
//! - `golden_*` tests freeze this crate's own output for each `examples/*.json` fixture the
//!   first time it is manually verified spec-conformant (e.g. via an independent CBOR
//!   decoder), then fail loudly on any future *unintentional* wire-format change. Golden
//!   fixtures live in `tests/golden/*.hex`; regenerate with `UPDATE_GOLDEN=1 cargo test`
//!   only after confirming the new bytes are still correct.
//! - `structural_*` tests decode the output independently (via `ciborium::Value`, not this
//!   crate's own `Serialize` impls) and assert the shape CDDL requires, without depending on
//!   a full external schema engine.
//! - `shorthand_and_standard_form_are_byte_identical` locks in that parse.rs's
//!   `suit-condition-version` convenience expansion produces exactly the CBOR a
//!   human-authored, spec-literal `suit-directive-try-each` would.

use std::fs::{self, File};
use std::io::BufReader;

use ciborium::Value;
use sha256::Sha256Digest;
use taylor::encode::{encode_envelope, encode_manifest};
use taylor::manifest::{SuitAuthentication, SuitDigest, SuitEnvelope};
use taylor::parse::parse;

/// Mirrors `main.rs`'s unsigned (digest-only) envelope construction.
fn build_envelope_cbor(json_path: &str) -> Vec<u8> {
    let mut reader = BufReader::new(File::open(json_path).unwrap_or_else(|e| {
        panic!("failed to open fixture {json_path}: {e}");
    }));
    let manifest = parse(&mut reader).unwrap_or_else(|e| {
        panic!("failed to parse fixture {json_path}: {e}");
    });

    let manifest_cbor = encode_manifest(&manifest);
    let digest_hex = manifest_cbor.digest();
    let digest = hex::decode(&digest_hex).expect("sha256 digest hex must be valid");

    let envelope = SuitEnvelope {
        auth_block: SuitAuthentication {
            digest: SuitDigest {
                algorithm: "sha256".to_owned(),
                digest,
            },
            auth_blocks: Vec::new(),
        },
        manifest,
    };
    encode_envelope(&envelope)
}

fn golden_path(name: &str) -> String {
    format!("tests/golden/{name}.hex")
}

/// Compares `actual` against the checked-in golden fixture for `name`, or (only when
/// `UPDATE_GOLDEN=1` is set) overwrites it - an intentional, explicit escape hatch so
/// fixtures are never silently regenerated by a routine `cargo test` run.
fn assert_matches_golden(name: &str, actual: &[u8]) {
    let path = golden_path(name);
    let actual_hex = hex::encode(actual);

    if std::env::var_os("UPDATE_GOLDEN").is_some() {
        fs::write(&path, &actual_hex).unwrap_or_else(|e| panic!("failed to write {path}: {e}"));
        return;
    }

    let expected_hex = fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "missing golden fixture {path}: {e}\n\
             run with UPDATE_GOLDEN=1 after manually verifying the new output is spec-conformant"
        )
    });
    assert_eq!(
        actual_hex,
        expected_hex.trim(),
        "encoded output for {name} no longer matches tests/golden/{name}.hex.\n\
         If this change is intentional and spec-conformant, rerun with UPDATE_GOLDEN=1."
    );
}

macro_rules! golden_test {
    ($test_name:ident, $fixture:literal) => {
        #[test]
        fn $test_name() {
            let cbor = build_envelope_cbor(concat!("examples/", $fixture, ".json"));
            assert_matches_golden($fixture, &cbor);
        }
    };
}

