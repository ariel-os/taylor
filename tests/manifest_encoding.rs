/// Decodes with `ciborium::Value` (independent of this crate's own `Serialize` impls) and
/// checks the structural invariants `SUIT_Envelope`/`SUIT_Manifest` require, standing in for
/// the CDDL conformance checks a working `cddl` validator would otherwise provide.
fn decode_envelope(cbor: &[u8]) -> (u64, Value) {
    assert_eq!(&cbor[0..2], &[0xD8, 0x6B], "envelope must be tagged 107");
    let value: Value = ciborium::de::from_reader(&cbor[2..]).expect("envelope must be valid CBOR");
    let Value::Map(entries) = &value else {
        panic!("SUIT_Envelope must be a CBOR map, got {value:?}");
    };
    // suit-authentication-wrapper (2) and suit-manifest (3) are the only required keys.
    let keys: Vec<i128> = entries
        .iter()
        .map(|(k, _)| {
            k.as_integer()
                .expect("envelope keys must be integers")
                .into()
        })
        .collect();
    assert!(
        keys.contains(&2),
        "envelope missing suit-authentication-wrapper (key 2)"
    );
    assert!(keys.contains(&3), "envelope missing suit-manifest (key 3)");
    (keys.len() as u64, value)
}

fn map_get<'a>(value: &'a Value, key: i128) -> Option<&'a Value> {
    value
        .as_map()?
        .iter()
        .find(|(k, _)| k.as_integer().map(Into::into) == Some(key))
        .map(|(_, v)| v)
}

#[test]
fn structural_envelope_and_manifest_shape() {
    let cbor = build_envelope_cbor("examples/manifest-handler.json");
    let (_, envelope) = decode_envelope(&cbor);

    let manifest_bstr = map_get(&envelope, 3)
        .unwrap()
        .as_bytes()
        .expect("suit-manifest must be a bstr");
    let manifest: Value = ciborium::de::from_reader(manifest_bstr.as_slice()).unwrap();

    // suit-manifest-version (1), suit-manifest-sequence-number (2), suit-common (3) are
    // mandatory; suit-install (20) is present because manifest-handler.json defines it.
    for required_key in [1i128, 2, 3, 20] {
        assert!(
            map_get(&manifest, required_key).is_some(),
            "SUIT_Manifest missing required key {required_key}"
        );
    }

    let common_bstr = map_get(&manifest, 3).unwrap().as_bytes().unwrap();
    let common: Value = ciborium::de::from_reader(common_bstr.as_slice()).unwrap();
    // suit-common-components (2) and suit-shared-sequence (4), per SUIT_Common.
    assert!(
        map_get(&common, 2).is_some(),
        "SUIT_Common missing suit-components (key 2)"
    );
    assert!(
        map_get(&common, 4).is_some(),
        "SUIT_Common missing suit-shared-sequence (key 4)"
    );
}

/// A `suit-directive-try-each` branch's argument must be an ARRAY of bstr-wrapped command
/// sequences (one per branch), never a bare command sequence - the mistake the shorthand's
/// hand-written equivalent is easy to make.
#[test]
fn structural_try_each_branches_are_bstr_wrapped_array_elements() {
    let cbor = build_envelope_cbor("examples/manifest-handler-standard.json");
    let (_, envelope) = decode_envelope(&cbor);
    let manifest_bstr = map_get(&envelope, 3).unwrap().as_bytes().unwrap();
    let manifest: Value = ciborium::de::from_reader(manifest_bstr.as_slice()).unwrap();
    let common_bstr = map_get(&manifest, 3).unwrap().as_bytes().unwrap();
    let common: Value = ciborium::de::from_reader(common_bstr.as_slice()).unwrap();
    let shared_bstr = map_get(&common, 4).unwrap().as_bytes().unwrap();
    let shared: Value = ciborium::de::from_reader(shared_bstr.as_slice()).unwrap();

    let flat = shared
        .as_array()
        .expect("shared sequence must be a flat array");
    // Find the try-each command (code 15) among the (code, arg) pairs.
    let mut found = false;
    let mut i = 0;
    while i < flat.len() {
        if flat[i].as_integer() == Some(15.into()) {
            found = true;
            let branches = flat[i + 1]
                .as_array()
                .expect("try-each argument must be an array");
            assert_eq!(
                branches.len(),
                3,
                "expected one branch per acceptable version"
            );
            for branch in branches {
                assert!(
                    branch.as_bytes().is_some(),
                    "each branch must be a bstr, not inlined"
                );
            }
        }
        i += 2;
    }
    assert!(
        found,
        "expected a suit-directive-try-each (code 15) in the shared sequence"
    );
}

/// `parse()` must reject malformed/unknown input with `Err`, not panic, for the cases it
/// already documents as returning `Error` (unknown command keys).
#[test]
fn unsupported_command_key_is_rejected_not_ignored() {
    let dir = std::env::temp_dir();
    let path = dir.join("taylor_test_unknown_command.json");
    fs::write(
        &path,
        r#"{
            "version": 1,
            "sequence-number": 1,
            "suit-common": { "suit-components": [["00"]], "suit-shared-sequence": [] },
            "sequence": { "payload-installation": [ {"suit-directive-nonexistent": 1} ] }
        }"#,
    )
    .unwrap();

    let mut reader = BufReader::new(File::open(&path).unwrap());
    let result = parse(&mut reader);
    fs::remove_file(&path).ok();

    assert!(
        result.is_err(),
        "unknown command keys must not be silently accepted"
    );
}
